"""Generate src/special/constants.mbt with mpmath.

Every coefficient the special functions use comes from here rather than
being copied by hand from a table, so a typo cannot hide in a constant.

    uv run --no-project --with mpmath python -I scripts/gen_special_constants.py
"""

import pathlib

from mpmath import mp, mpf, bernoulli, zeta, euler, polygamma, findroot, digamma, nstr

mp.dps = 60
ROOT = pathlib.Path(__file__).resolve().parent.parent


def lit(x):
    """Nearest double as a MoonBit literal with 17 significant digits."""
    s = nstr(mpf(float(x)), 17, min_fixed=-1, max_fixed=-1)
    m, _, e = s.partition("e")
    if "." not in m:
        m += ".0"
    return m + ("e" + e if e else "")


def split(x):
    """x as hi + lo, hi the nearest double, lo the next correction."""
    hi = float(x)
    lo = float(x - mpf(hi))
    return hi, lo


def array(name, values, doc):
    body = ",\n".join(f"  {lit(v)}" for v in values)
    return f"///|\n/// {doc}\nlet {name} : FixedArray[Double] = [\n{body},\n]\n"


def main():
    out = [
        "// Generated by scripts/gen_special_constants.py with mpmath; do not edit.\n",
        f"///|\nlet euler_gamma : Double = {lit(euler)}\n",
        array(
            "zeta_minus_one",
            [zeta(k) - 1 for k in range(2, 66)],
            "ζ(k) - 1 for k = 2, 3, ..., 65 (index k - 2).",
        ),
        array(
            "stirling",
            [bernoulli(2 * k) / (2 * k * (2 * k - 1)) for k in range(1, 11)],
            "B(2k)/(2k(2k - 1)), k = 1..10: lnΓ(x) - Stirling = Σ c_k x^(1-2k).",
        ),
        array(
            "digamma_asym",
            [bernoulli(2 * k) / (2 * k) for k in range(1, 11)],
            "B(2k)/(2k), k = 1..10: ψ(x) ~ ln x - 1/(2x) - Σ c_k x^(-2k).",
        ),
        array(
            "trigamma_asym",
            [bernoulli(2 * k) for k in range(1, 11)],
            "B(2k), k = 1..10: ψ'(x) ~ 1/x + 1/(2x²) + Σ c_k x^(-2k-1).",
        ),
    ]
    root = findroot(digamma, mpf("1.46"))
    hi, lo = split(root)
    out.append(f"///|\n/// The positive zero of ψ, as hi + lo.\nlet digamma_root_hi : Double = {lit(hi)}\n")
    out.append(f"///|\nlet digamma_root_lo : Double = {lit(lo)}\n")
    out.append(
        array(
            "digamma_root_taylor",
            [polygamma(k, root) / mp.factorial(k) for k in range(1, 41)],
            "ψ^(k)(x0)/k! for k = 1..40 at the zero x0: ψ(x0 + z) = Σ c_k z^k.",
        )
    )
    (ROOT / "src/special/constants.mbt").write_text("\n".join(out))
    print("ok, root", root)


main()
